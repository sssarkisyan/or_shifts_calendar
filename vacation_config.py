"""Настройки портала заявок на отпуск (врачи) — отредактируйте перед запуском.

Список сотрудников берётся из config.py (тот же ростер, что и в форме
пожеланий по графику), здесь — только правила отпусков.
"""
import datetime

# Год, на который составляется график отпусков (выбран по умолчанию в форме).
PLAN_YEAR = 2027

# Положено дней отпуска за год — всем одинаково. Праздничные нерабочие дни
# внутри отпуска в эти дни не входят (ст. 120 ТК РФ) — портал считает это сам.
BASE_DAYS = 31

# Остаток неиспользованных дней за прошлые периоды — прибавляется к BASE_DAYS.
# Пример: "Исхаков Руслан Ильдарович": 5,
CARRYOVER_DAYS = {
}

# Отпуска двух сотрудников этих типов (тип — из config.py) могут пересекаться
# не больше MAX_OVERLAP_DAYS календарных дней. Совместители, договорники,
# заведующий и профессор этим правилом не ограничены (совместители уходят в
# отпуск одновременно с отпуском по основному месту работы).
OVERLAP_KINDS = {"основной"}
MAX_OVERLAP_DAYS = 7
# И одновременно в отпуске — не больше стольких сотрудников этих типов.
MAX_CONCURRENT_MAIN = 2

# Кто чьи отпуска видит в календаре на странице сотрудника (по типам из
# config.py): каждый видит коллег из своей группы. Кто не входит ни в одну
# группу (совместители, договорники), видит в календаре только свои отпуска —
# ограничений по датам у них нет. На правила выше не влияет — лимиты
# по-прежнему считаются только по OVERLAP_KINDS.
CALENDAR_GROUPS = [
    {"основной"},
    {"заведующий", "профессор"},
]

# Хотя бы одна часть отпуска — не меньше стольких дней (ст. 125 ТК РФ).
MIN_LONG_PART = 14

# После этой даты сотрудники не могут добавлять/удалять периоды (только
# смотреть статус). None — без ограничения. Пример: datetime.date(2026, 12, 1)
SUBMISSION_DEADLINE = None


def carryover(name):
    return CARRYOVER_DAYS.get(name, 0)


def entitlement(name):
    return BASE_DAYS + carryover(name)


assert SUBMISSION_DEADLINE is None or isinstance(SUBMISSION_DEADLINE, datetime.date)
